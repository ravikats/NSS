-- Local FILE_FORMATS rows the bin-service needs, and why.
--
-- FILE_UPLOAD_LOG.UPL_FOR_CODE has FK_UPL_FOR_CODE -> FILE_FORMATS.FOR_CODE in
-- the local replica, so a BIN load fails with ORA-02291 unless the code the
-- service is configured with has a parent row. The UAT schema only carries
-- JAYWAN BIN FILE (61) and MERCURY BIN FILE (121) plus OMANNET BIN FILE (101),
-- while the Java/Go service config uses 2 (Mastercard) and 3 (Visa).
--
-- FOR_CODE is GENERATED ALWAYS AS IDENTITY, which refuses explicit values, so
-- it is switched to BY DEFAULT first. That is a LOCAL-RECIPE change only.
--
-- Apply once, as NETWORK_SETTLEMENT_UAT:
--   sqlplus NETWORK_SETTLEMENT_UAT/***@//localhost:1521/FREEPDB1 @file_formats_bin_codes.sql

ALTER TABLE FILE_FORMATS MODIFY (FOR_CODE GENERATED BY DEFAULT AS IDENTITY);

