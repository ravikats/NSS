-- -----------------------------------------------------------------------------
-- 3. Add the 13 entity columns missing from the legacy IRF_CALLBACK table
--    (115,314 existing rows; all columns nullable, Oracle default).
--    Sizes match the handover record (§7.2) and IRFCallbackEntity.
-- -----------------------------------------------------------------------------
DECLARE
    v_cnt NUMBER;
BEGIN
    FOR c IN (
        SELECT 'ICB_CARD_CLASSIFICATION' col, 'VARCHAR2(50)'  typ FROM dual UNION ALL
        SELECT 'ICB_CP_MID',             'VARCHAR2(30)'       FROM dual UNION ALL
        SELECT 'ICB_DOM_INTL_FLAG',      'CHAR(1)'            FROM dual UNION ALL
        SELECT 'ICB_FIXED',              'NUMBER'             FROM dual UNION ALL
        SELECT 'ICB_IRF_AMOUNT',         'NUMBER'             FROM dual UNION ALL
        SELECT 'ICB_PERCENTAGE',         'NUMBER'             FROM dual UNION ALL
        SELECT 'ICB_TXN_AMOUNT',         'NUMBER'             FROM dual UNION ALL
        SELECT 'ICB_IS_CREDIT',          'NUMBER(1)'          FROM dual UNION ALL
        SELECT 'ICB_JOB_NUMBER',         'NUMBER'             FROM dual UNION ALL
        SELECT 'ICB_IRD_CODE',           'VARCHAR2(10)'       FROM dual UNION ALL
        SELECT 'ICB_MTI',                'VARCHAR2(4)'        FROM dual UNION ALL
        SELECT 'ICB_RRN',                'VARCHAR2(12)'       FROM dual UNION ALL
        SELECT 'ICB_UNIQUE_ID',          'VARCHAR2(50)'       FROM dual
    ) LOOP
        SELECT COUNT(*) INTO v_cnt FROM user_tab_columns
         WHERE table_name = 'IRF_CALLBACK' AND column_name = c.col;
        IF v_cnt = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE IRF_CALLBACK ADD (' || c.col || ' ' || c.typ || ')';
            DBMS_OUTPUT.PUT_LINE('ADDED: IRF_CALLBACK.' || c.col || ' ' || c.typ);
        ELSE
            DBMS_OUTPUT.PUT_LINE('SKIP (already exists): IRF_CALLBACK.' || c.col);
        END IF;
    END LOOP;
END;
/

