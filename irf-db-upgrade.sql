  FROM user_tab_columns
 WHERE table_name IN ('OMAN_NET_IRF', 'OMANNET_BIN_DATA', 'IRF_CALLBACK')
   AND (table_name IN ('OMAN_NET_IRF', 'OMANNET_BIN_DATA')
        OR column_name IN ('ICB_CARD_CLASSIFICATION','ICB_CP_MID','ICB_DOM_INTL_FLAG',
                           'ICB_FIXED','ICB_IRF_AMOUNT','ICB_PERCENTAGE','ICB_TXN_AMOUNT',
                           'ICB_IS_CREDIT','ICB_JOB_NUMBER','ICB_IRD_CODE','ICB_MTI',
                           'ICB_RRN','ICB_UNIQUE_ID'))
 ORDER BY table_name, column_id;
